//Hacemos algoritmo por inserción
void    alg_insertion(t_cll *stack_a)
{
    t_cll   *aux;
    int     index;
    
    aux->head = NULL;
    aux->size = 0;
    while (index++ < stack_a->size)
    {
        ft_pa(stack_a->head, aux->head->next);
    }
    
}
